#!/usr/bin/env python3
"""Generate tokenizer ground truth from corpus files.

Requires:
  - python-jieba  (pacman -S python-jieba)

Note: Japanese ground truth is hand-annotated (ground-truth/ja-manual.json),
not generated by this script.

Usage:
    python3 tests/tokenizer-bench/gen-ground-truth.py
"""
import json
from pathlib import Path

BENCH_DIR = Path(__file__).resolve().parent
CORPUS_ZH = BENCH_DIR / "corpus-zh.txt"
OUT_DIR = BENCH_DIR / "ground-truth"


def generate_zh():
    import jieba

    lines = [l.strip() for l in CORPUS_ZH.read_text().splitlines() if l.strip()]
    results = []
    for line in lines:
        tokens = list(jieba.cut(line))
        results.append({"input": line, "tokens": tokens})

    OUT_DIR.mkdir(exist_ok=True)
    out_path = OUT_DIR / "zh-jieba.json"
    out_path.write_text(json.dumps(results, ensure_ascii=False, indent=2) + "\n")
    print(f"wrote {len(results)} entries to {out_path}")


if __name__ == "__main__":
    generate_zh()
